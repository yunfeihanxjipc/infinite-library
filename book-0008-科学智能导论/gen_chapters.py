        tags = len(re.findall(r"\\tag\{", text))
        examples = len(re.findall(r"\*\*例 \d+\.\d+", text))
        refs = len(re.findall(r"^\[\d+\]", text, re.M))
        figs = len(re.findall(r"【图 \d+-", text))
        print(f"ch{num}: lines={lines:3d} tags={tags:2d} examples={examples} figs={figs} refs={refs}")
